"""Helpers for unattended ACT PyBullet eval sweeps."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Dict, Optional, Sequence, Tuple

_COVERAGE_RE = re.compile(
    r"^Path coverage(?:\s*\((?P<name>[^)]+)\))?:\s*(?P<pct>[-+]?\d*\.?\d+)%\s*$",
    re.MULTILINE,
)
_COLLISION_RE = re.compile(
    r"Constraint Violations Summary:.*?state:.*?violations=(?P<n>\d+)/",
    re.DOTALL,
)


def resolve_pretrained_model(output_dir: Path, checkpoint: str = "last") -> Path:
    """Return ``.../checkpoints/<checkpoint>/pretrained_model`` under a train run."""
    output_dir = Path(output_dir)
    ckpt = str(checkpoint).strip()
    if ckpt in ("", ".", "..") or "/" in ckpt or "\\" in ckpt:
        raise ValueError(
            f"checkpoint must be a single segment like 'last', got {checkpoint!r}"
        )
    model = output_dir / "checkpoints" / ckpt / "pretrained_model"
    if not (model / "config.json").is_file():
        raise FileNotFoundError(
            f"missing ACT checkpoint config: {model / 'config.json'}"
        )
    return model.resolve()


def action_width_from_config(config: Dict[str, Any]) -> int:
    out = config.get("output_features") or {}
    action = out.get("action") or {}
    shape = action.get("shape")
    if not shape:
        raise ValueError("checkpoint config missing output_features.action.shape")
    return int(shape[0])


def infer_teleop_from_action_width(nu: int) -> str:
    """Map trained action width to launch teleop mode (no override)."""
    if nu == 9:
        return "act"
    if nu in (3, 6):
        return "act_ee"
    raise ValueError(
        f"cannot infer teleop from action width {nu}; expected 9 (act) or 3/6 (act_ee)"
    )


def infer_teleop_from_checkpoint(pretrained_model: Path) -> Tuple[str, int]:
    config = json.loads((Path(pretrained_model) / "config.json").read_text())
    nu = action_width_from_config(config)
    return infer_teleop_from_action_width(nu), nu


def parse_metrics_summary(text: str) -> Dict[str, Any]:
    """Extract path coverage (and optional state violations) from summary.txt."""
    coverages: Dict[str, float] = {}
    overall: Optional[float] = None
    for match in _COVERAGE_RE.finditer(text):
        pct = float(match.group("pct"))
        name = match.group("name")
        if name is None:
            overall = pct / 100.0
        else:
            coverages[name] = pct / 100.0
    state_violations = None
    m = _COLLISION_RE.search(text)
    if m:
        state_violations = int(m.group("n"))
    return {
        "path_coverage": overall,
        "path_coverage_by_name": coverages,
        "state_violations": state_violations,
    }


def find_session_metrics(trial_root: Path) -> Optional[Path]:
    """Return the newest ``**/metrics/summary.txt`` under a trial log root."""
    trial_root = Path(trial_root)
    summaries = sorted(
        trial_root.glob("**/metrics/summary.txt"),
        key=lambda p: p.stat().st_mtime,
    )
    return summaries[-1] if summaries else None


def aggregate_eval_trials(trial_records: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
    coverages = [
        float(r["path_coverage"])
        for r in trial_records
        if r.get("path_coverage") is not None
    ]
    agg: Dict[str, Any] = {
        "n_trials": len(trial_records),
        "n_with_coverage": len(coverages),
        "path_coverage_mean": (
            float(sum(coverages) / len(coverages)) if coverages else None
        ),
        "path_coverage_min": float(min(coverages)) if coverages else None,
        "path_coverage_max": float(max(coverages)) if coverages else None,
        "trials": list(trial_records),
    }
    return agg


def write_eval_overlay(
    path: Path,
    *,
    log_dir: Path,
    duration_s: Optional[float] = None,
    ctrl_rate: Optional[float] = None,
) -> Path:
    """Write a ctrl_config overlay: absolute log_dir, no metadata prompt."""
    path = Path(path)
    log_dir = Path(log_dir).resolve()
    lines = [
        "# Auto-generated by eval_act_smoke — do not edit by hand.",
        "logging:",
        f"  log_dir: {json.dumps(str(log_dir))}",
        "  prompt_trial_metadata: false",
    ]
    if ctrl_rate is not None:
        rate = float(ctrl_rate)
        if rate <= 0.0:
            raise ValueError(f"ctrl_rate must be positive, got {rate}")
        lines.extend(
            [
                "controller:",
                f"  ctrl_rate: {rate}",
            ]
        )
    if duration_s is not None:
        lines.extend(
            [
                "simulation:",
                f"  duration: {float(duration_s)}",
            ]
        )
    path.write_text("\n".join(lines) + "\n")
    return path
